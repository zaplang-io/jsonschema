#!/usr/bin/env python3
"""Embed the unmodified, vendored official meta-schemas for offline runtime use."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
lines = ['# Generated by tools/generate-metaschemas.py; see vendor/metaschemas/LICENSE.',
         'def resources() -> dict[str, JsonValue]:', '    dict[str, JsonValue] schemas = {}']
for source in sorted((root / 'vendor/metaschemas').glob('*.json')):
    schema = json.loads(source.read_text())
    uri = schema['$id'].rstrip('#')
    encoded = json.dumps(json.dumps(schema, separators=(',', ':'), ensure_ascii=False), ensure_ascii=False)
    lines.append(f'    schemas[{json.dumps(uri)}] = json.loads({encoded})')
lines.append('    return schemas')
(root / 'src/jsonschema/metaschemas.zap').write_text('\n'.join(lines) + '\n')
